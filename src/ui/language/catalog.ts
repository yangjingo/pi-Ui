export const UI_LOCALES = {
  en: {
    aliases: ['en', 'en-us', 'en-gb'],
    messages: EN_MESSAGES,
  },
  'zh-CN': {
    aliases: ['zh', 'zh-cn', 'zh-hans'],
    messages: ZH_CN_MESSAGES,
  },
} as const;

export type UiLanguage = keyof typeof UI_LOCALES;
export const DEFAULT_UI_LANGUAGE: UiLanguage = 'en';

export function resolveMessage(
  language: UiLanguage,
  key: UiMessageKey,
  parameters: MessageParameters = {},
): string {
  const value = UI_LOCALES[language].messages[key];
  const template = typeof value === 'string'
    ? value
    : pluralTemplate(language, value, parameters.count);
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(parameters, name) ? String(parameters[name]) : match
  ));
}

function pluralTemplate(
  language: UiLanguage,
  message: PluralMessage,
  count: string | number | undefined,
): string {
  const numeric = Number(count);
  if (!Number.isFinite(numeric)) return message.other;
  const category = new Intl.PluralRules(language).select(numeric);
  return message[category] || message.other;
}
